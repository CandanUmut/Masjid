// Regenerates js/tzdata.js from the IANA zone table (tzdata's zone.tab): one principal city per zone,
// with its country. Used to name a time zone offline. Run: node tools/make-tzdata.cjs [path/to/zone.tab]
const fs = require("fs");
const path = require("path");
const src = process.argv[2] || "/usr/share/zoneinfo/zone.tab";
const dms = (s, degDigits) => {
  const sign = s[0] === "-" ? -1 : 1;
  const d = Number(s.slice(1, 1 + degDigits));
  const m = Number(s.slice(1 + degDigits, 3 + degDigits));
  const sec = Number(s.slice(3 + degDigits) || 0);
  return sign * (d + m / 60 + sec / 3600);
};
const rows = fs
  .readFileSync(src, "utf8")
  .split("\n")
  .filter((l) => l && !l.startsWith("#"))
  .map((l) => {
    const [cc, coords, tz] = l.split("\t");
    const m = coords.match(/^([+-]\d+)([+-]\d+)$/);
    const lat = dms(m[1], 2);
    const lng = dms(m[2], 3);
    return `${cc},${lat.toFixed(1)},${lng.toFixed(1)},${tz}`;
  });
const out = `// Generated by tools/make-tzdata.cjs from IANA tzdata zone.tab (public domain). Do not edit.
// Each entry: country code, latitude, longitude of the zone's principal city, IANA zone.
export const ZONES = "${rows.join(";")}";
`;
fs.writeFileSync(path.join(__dirname, "..", "js", "tzdata.js"), out);
console.log(`${rows.length} zones, ${out.length} bytes`);
